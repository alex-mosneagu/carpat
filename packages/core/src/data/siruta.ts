export function searchLocalities(query: string, countyCode?: string): Locality[] {
  const normalized = query.toLowerCase();
  let results = LOCALITIES.filter((l) => l.name.toLowerCase().includes(normalized));

  if (countyCode) {
    results = results.filter((l) => l.countyCode === countyCode);
  }

  return results.slice(0, 50);
}

